# Faça um programa que peça o nome de um curso
# e a quantidade de horas que o aluno estuda nesse curso.
# Depois, mostre essas informações no terminal.

# Entrada de dados
curso = input("insira o nome do curso: ")
horas = int(input("Insira a carga horária (em horas) deste curso: "))

# Processamento computacional

# Saída de informação
print(f"\nNome do curso: {curso}")
print(f"Carga horária: {horas} horas")