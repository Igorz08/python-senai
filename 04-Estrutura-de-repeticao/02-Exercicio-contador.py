# Criar uma variável chamada contador começando com 1.
# Utilizar um while para verificar se o contador é menor ou igual a 10.
# Mostrar o número atual no console.
# Aumentar o contador em 1 a cada repetição.

contador = 1

while contador <= 10:

    print(f"Contador: {contador}")
    contador = contador + 1

print("Contador chegou ao 11, fim.")