# Entrada de dados básicos
numero1 = int(input("Digite o primeiro número: "))
numero2 = int(input("Digite o segundo número: "))

# Processamento computacional
soma = numero1 + numero2
sub = numero1 - numero2
multi = numero1 * numero2
div = numero1 / numero2

# Saida da informação
print(f"\nA soma dos números é: {soma} \n")
print(f"A subtração dos números é: {sub} \n")
print(f"A multiplicação dos números é: {multi} \n")
print(f"A divisão dos números é: {div}")